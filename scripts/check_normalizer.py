"""Measure the WER the scoring pipeline gives a perfect transcript.

The human `raw_text` is cased and punctuated like a model's output. Scoring
it as a hypothesis against `standardized_text` shows how much error the
normalisation itself introduces: the lowest WER any model could get when
it writes standard orthography. Writes reports/normalizer.md.

    python scripts/check_normalizer.py --config configs/local.yaml
"""

from __future__ import annotations

import argparse
from pathlib import Path

from voxnor.analysis import score_utterances, summarize
from voxnor.config import load_config
from voxnor.data import SPLITS, load_metadata


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", required=True)
    parser.add_argument("--examples", type=int, default=15)
    parser.add_argument("--out", default="reports/normalizer.md")
    args = parser.parse_args()

    cfg = load_config(args.config)
    lines = [
        "# Normaliser check",
        "",
        "Human `raw_text` scored as a hypothesis against `standardized_text`, with",
        "the same pipeline as model output. Generated by `scripts/check_normalizer.py`.",
        "",
        "| split | utterances scored | WER | CER | utterances with any error |",
        "| --- | --- | --- | --- | --- |",
    ]
    mismatches = []
    for split in SPLITS:
        meta = load_metadata(cfg.data, split)
        scored = score_utterances(meta.assign(hypothesis=meta["raw_text"], seen_speaker=False))
        summary = summarize(scored, n_resamples=200)
        included = scored[scored["excluded"].isna()]
        wrong = included[
            included["substitutions"] + included["deletions"] + included["insertions"] > 0
        ]
        lines.append(
            f"| {split} | {summary['utterances_scored']} "
            f"| {summary['overall']['wer']['value']:.3%} "
            f"| {summary['overall']['cer']['value']:.3%} | {len(wrong)} |"
        )
        mismatches.append(wrong.assign(split=split))

    wrong = mismatches[-1]
    lines += [
        "",
        f"Examples from the test split ({min(args.examples, len(wrong))} of {len(wrong)}):",
        "",
        "| reference | normalised raw_text |",
        "| --- | --- |",
    ]
    for row in wrong.sample(min(args.examples, len(wrong)), random_state=0).itertuples():
        lines.append(f"| {row.reference} | {row.hypothesis} |")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()

"""Descriptive statistics of the splits: sizes, regions, speaker overlap, transcript quirks."""

from __future__ import annotations

from typing import Any

import pandas as pd

from voxnor.data import exclude_speakers

# Markers in `raw_text` that `standardized_text` maps or drops.
ANNOTATION_PATTERNS = {
    "hesitation <ee>": r"<ee>",
    "hesitation <qq>": r"<qq>",
    "hesitation <mm>": r"<mm>",
    "<INAUDIBLE>": r"<INAUDIBLE>",
    # e.g. `vi|1`; the label avoids "|", which would break Markdown tables.
    "numbered word marker": r"\w\|\d",
}


def split_summary(meta: pd.DataFrame) -> dict[str, Any]:
    return {
        "utterances": len(meta),
        "hours": round(meta["duration"].sum() / 3600, 2),
        "speakers": meta["speaker_id"].nunique(),
        "meetings": meta["full_audio_file"].nunique(),
        "mean_duration_s": round(meta["duration"].mean(), 2),
        "hours_by_region": _hours_by(meta, "region"),
        "speakers_by_region": meta.groupby("region")["speaker_id"].nunique().to_dict(),
        "hours_by_gender": _hours_by(meta, "gender"),
        "utterances_with": {
            name: int(meta["raw_text"].str.contains(pattern).sum())
            for name, pattern in ANNOTATION_PATTERNS.items()
        },
    }


def speaker_overlap(train: pd.DataFrame, held_out: pd.DataFrame) -> dict[str, Any]:
    """How much of `held_out` is spoken by speakers who also occur in `train`."""
    seen = held_out["speaker_id"].isin(set(train["speaker_id"]))
    unseen = held_out[~seen]
    return {
        "speakers_seen_in_train": int(held_out.loc[seen, "speaker_id"].nunique()),
        "speakers_total": int(held_out["speaker_id"].nunique()),
        "utterance_share_seen": round(float(seen.mean()), 3),
        "unseen_utterances": len(unseen),
        "unseen_hours": round(unseen["duration"].sum() / 3600, 2),
        "unseen_hours_by_region": _hours_by(unseen, "region"),
        "shared_meetings": len(set(train["full_audio_file"]) & set(held_out["full_audio_file"])),
    }


def build_report(splits: dict[str, pd.DataFrame]) -> dict[str, Any]:
    train, validation, test = splits["train"], splits["validation"], splits["test"]
    return {
        "splits": {name: split_summary(meta) for name, meta in splits.items()},
        "speaker_overlap": {
            "validation": speaker_overlap(train, validation),
            "test": speaker_overlap(train, test),
            # The training set actually used (test speakers removed).
            "validation vs train without test speakers": speaker_overlap(
                exclude_speakers(train, test), validation
            ),
        },
        "train_without_held_out_speakers": {
            "test": split_summary(exclude_speakers(train, test)),
            "validation+test": split_summary(exclude_speakers(train, validation, test)),
        },
        "speaker_region_is_constant": bool(
            (pd.concat(splits.values()).groupby("speaker_id")["region"].nunique() <= 1).all()
        ),
    }


def render_markdown(report: dict[str, Any], source: str) -> str:
    splits = report["splits"]
    names = list(splits)
    regions = sorted({r for s in splits.values() for r in s["hours_by_region"]})
    lines = [
        "# Data report",
        "",
        f"Source: `{source}`. Generated by `scripts/data_report.py`; do not edit by hand.",
        "",
        "## Splits",
        "",
        _table(
            ["", *names],
            [
                [key, *(splits[n][key] for n in names)]
                for key in ("utterances", "hours", "speakers", "meetings", "mean_duration_s")
            ],
        ),
        "",
        "Hours by region (number of speakers in brackets):",
        "",
        _table(
            ["region", *names],
            [
                [
                    region,
                    *(
                        f"{splits[n]['hours_by_region'].get(region, 0)} "
                        f"({splits[n]['speakers_by_region'].get(region, 0)})"
                        for n in names
                    ),
                ]
                for region in regions
            ],
        ),
        "",
        "## Speaker overlap with train",
        "",
        "Splits are by meeting date (no meeting is shared), but members of",
        "parliament speak on many days.",
        "",
        _table(
            ["", *report["speaker_overlap"]],
            [
                [key, *(o[key] for o in report["speaker_overlap"].values())]
                for key in (
                    "speakers_seen_in_train",
                    "speakers_total",
                    "utterance_share_seen",
                    "unseen_utterances",
                    "unseen_hours",
                    "unseen_hours_by_region",
                    "shared_meetings",
                )
            ],
        ),
        "",
        "Training data left after removing held-out speakers:",
        "",
        _table(
            ["removed speakers of", "utterances", "hours", "speakers", "hours by region"],
            [
                [name, s["utterances"], s["hours"], s["speakers"], s["hours_by_region"]]
                for name, s in report["train_without_held_out_speakers"].items()
            ],
        ),
        "",
        "## Transcript annotations",
        "",
        "Utterances whose `raw_text` contains each marker. `standardized_text` maps",
        "hesitations to `eee`/`qqq`/`mmm` and drops the other markers.",
        "",
        _table(
            ["marker", *names],
            [
                [marker, *(splits[n]["utterances_with"][marker] for n in names)]
                for marker in ANNOTATION_PATTERNS
            ],
        ),
        "",
    ]
    return "\n".join(lines)


def _hours_by(meta: pd.DataFrame, column: str) -> dict[str, float]:
    hours = meta.groupby(column)["duration"].sum() / 3600
    return {key: round(float(value), 2) for key, value in hours.items()}


def _table(header: list[Any], rows: list[list[Any]]) -> str:
    def fmt(row):
        return "| " + " | ".join(str(cell) for cell in row) + " |"

    return "\n".join([fmt(header), fmt(["---"] * len(header)), *(fmt(r) for r in rows)])
